const DICTIONARIES = { ru: RU, en: EN };

export function language() {
  const code = state.preferences['ui.language'];
  return DICTIONARIES[code] ? code : DEFAULT_LANGUAGE;
}

export function locale() {
  const found = LANGUAGES.find((item) => item.code === language());
  return found ? found.locale : LANGUAGES[0].locale;
}

export function t(key, vars) {
  const source = DICTIONARIES[language()][key] ?? RU[key] ?? key;
  if (!vars) return source;
  return source.replace(/\{(\w+)\}/g, (match, name) =>
    Object.hasOwn(vars, name) ? String(vars[name]) : match
  );
}
